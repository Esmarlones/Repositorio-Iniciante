public class Example6 {
    public static void main(String[] args){
        int dia = 2;

        switch(dia) {
            case 1:
                System.out.println("Domingo");
                

            case 2:
                System.out.println("Segunda");
                

            case 3:
                System.out.println("Terça-feira");
            
            default:
                System.out.println("Outro dia");
                

        }
    }
}
